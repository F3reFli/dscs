<h2>Changing the chunk format</h2>

<p>Bump <code>CHUNK_FORMAT</code> (<code>crypto/cipher.py</code>), keep the reading code for the previous formats, and pick the
processing based on <code>StoredFile.format</code> when downloading. A file already uploaded must never become unreadable.</p>
