<h2>Conventions</h2>

<ul>
  <li><strong>French</strong> in the code: comments, user-facing messages. The documentation exists in French and English.</li>
  <li><strong>Layers</strong>: follow the rules in <?= $c->link('concepts/architecture', null, 'dependency-rules') ?>. An interface
    only talks to the Vault.</li>
  <li><strong>No global computed at import time</strong>: pass paths through <code>Paths</code>.</li>
  <li><strong>Secrets</strong>: a webhook token never leaves <code>config.toml</code>; in a message, use
    <code>WebhookRef.redacted</code>.</li>
  <li><strong>Errors</strong>: every expected error is a <code>DSCSError</code> (or subclass) with a message that says what to do.</li>
  <li><strong>Style</strong>: ruff, 120 columns, type annotations, <code>from __future__ import annotations</code>.</li>
  <li><strong>Tests</strong>: every feature or fix comes with its test (<?= $c->link('dev/tests') ?>).</li>
  <li><strong>Docs</strong>: a rule that changes updates <code>ARCHITECTURE.md</code> and the relevant page here, in both languages.</li>
</ul>

<h2>Adding a command</h2>

<?= $c->steps([
    '<p>If the operation is new, add a method to the <code>Vault</code> (<code>services/vault.py</code>) that delegates to <code>transfer/</code> or to a building block.</p>',
    '<p>Declare the subcommand in <code>cli/parser.py</code> (<code>sub.add_parser</code> + <code>set_defaults(func=…)</code>) and add its name to <code>COMMANDS</code>.</p>',
    '<p>Write <code>cmd_&lt;name&gt;(args) -&gt; int</code> in <code>cli/commands.py</code>: open the Vault with <code>with Vault.open()</code>, and <code>asyncio.run</code> for the network part.</p>',
    '<p>Test the parsing in <code>tests/unit/test_cli.py</code> and the behaviour in <code>tests/integration/</code>.</p>',
    '<p>Document it in ' . $c->link('guide/cli') . ' and ' . $c->link('reference/cli') . '.</p>',
]) ?>

<h2>Adding a screen or a key to the interface</h2>

<ul>
  <li>A modal screen goes into <code>tui/screens/</code>, a widget into <code>tui/widgets/</code>, exported by the folder's
    <code>__init__.py</code>.</li>
  <li>Styles go into <code>tui/app.tcss</code> (the accent colour is <code>$dscs-accent</code>, to keep in sync with
    <code>tui/theme.py</code>).</li>
  <li>A network action runs in a <code>@work(group="transfer")</code> and goes through the Vault.</li>
  <li>Add the key to the <code>tests/tui/test_app.py</code> scenario and to the table in <?= $c->link('guide/interface') ?>.</li>
</ul>

